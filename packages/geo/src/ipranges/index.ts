import type { AiBot } from '../types.js';
import { CidrSet } from './cidr.js';
import snapshot from './snapshot.json';

export { CidrSet, parseCidr, parseIp } from './cidr.js';
export type { ParsedCidr, ParsedIp } from './cidr.js';

export interface IpRangeList {
  url: string;
  vendor: string;
  bots: string[];
  creationTime: string | null;
  ipv4: string[];
  ipv6: string[];
}

export interface IpRangeSnapshot {
  /** Day the snapshot was built (YYYY-MM-DD). */
  asOf: string;
  note?: string;
  lists: IpRangeList[];
}

/** The bundled snapshot. Regenerated by scripts/refresh-ip-ranges.mjs; never fetched at runtime (AC 10). */
export const IP_RANGES: IpRangeSnapshot = snapshot;
export const IP_RANGES_AS_OF: string = IP_RANGES.asOf;

/** Same list whatever the scheme or a leading www. */
export function rangeKey(url: string): string {
  return url
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, '')
    .replace(/^www\./, '');
}

/** Decides whether an IP belongs to a bot's vendor: true inside, false outside, null when we hold no list for it. */
export type IpVerifier = (bot: AiBot, ip: string) => boolean | null;

export function createIpVerifier(snap: IpRangeSnapshot = IP_RANGES): IpVerifier {
  const sources = new Map<string, IpRangeList>();
  for (const l of snap.lists) sources.set(rangeKey(l.url), l);
  const sets = new Map<string, CidrSet>();
  return (bot, ip) => {
    if (!bot.ipRangesUrl) return null;
    const key = rangeKey(bot.ipRangesUrl);
    let set = sets.get(key);
    if (!set) {
      const list = sources.get(key);
      if (!list) return null;
      set = new CidrSet([...list.ipv4, ...list.ipv6]);
      sets.set(key, set);
    }
    return set.has(ip);
  };
}

/** Verifier over the bundled snapshot. */
export const verifyBotIp: IpVerifier = createIpVerifier();
